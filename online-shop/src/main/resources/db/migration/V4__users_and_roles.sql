-- Practice 7 (lecture week 12, slide 12): the user store for Spring Security.
-- Passwords are never stored, only their hashes; the {bcrypt} prefix of DelegatingPasswordEncoder lets the
-- algorithm be upgraded later without resetting passwords (slide 14). Real users go in through the app, and
-- demo users only through the dev-only seed (db/seed/V5__seed_demo_users.sql), so no known password
-- reaches a test or production database.

CREATE TABLE app_users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE
);

-- Usernames are unique regardless of letter case, like category names and product SKUs
CREATE UNIQUE INDEX ux_app_users_username_lower ON app_users (LOWER(username));

-- Many-to-many between a user and its roles. Spring Security sees each role as the authority ROLE_<role>.
CREATE TABLE user_roles (
    user_id BIGINT      NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    role    VARCHAR(32) NOT NULL,
    PRIMARY KEY (user_id, role),
    CONSTRAINT ck_user_roles_role CHECK (role IN ('CUSTOMER', 'ADMIN'))
);
